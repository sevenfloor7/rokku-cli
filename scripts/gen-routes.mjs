#!/usr/bin/env node
// Generates lib/routes.generated.mjs from rokku-backend's openapi/public.json: for every public route,
// its query parameters, whether it needs an Idempotency-Key, and its required body fields.
// The CLI sends requests only through routes listed there, so a route the backend renames or drops
// fails `npm test` (test/routes.mjs) instead of failing for users.
//   node scripts/gen-routes.mjs <path/to/public.json> [--check]
import {createHash} from "node:crypto";
import {readFileSync, writeFileSync} from "node:fs";

const [input, mode] = process.argv.slice(2);
if (!input) {
  process.stderr.write("Usage: node scripts/gen-routes.mjs <rokku-backend/openapi/public.json> [--check]\n" +
    "  e.g. git -C ../rokku-backend show origin/test:openapi/public.json > /tmp/public.json\n");
  process.exit(64);
}
const raw = readFileSync(input), spec = JSON.parse(raw);
const OUTPUT = new URL("../lib/routes.generated.mjs", import.meta.url);
const schema = ref => ref && spec.components.schemas[ref.split("/").pop()];

const routes = {};
for (const [path, methods] of Object.entries(spec.paths)) {
  for (const [method, operation] of Object.entries(methods)) {
    if (!["get", "post", "put", "patch", "delete"].includes(method)) continue;
    const parameters = operation.parameters ?? [];
    const body = schema(operation.requestBody?.content?.["application/json"]?.schema?.$ref);
    routes[`${method.toUpperCase()} ${path}`] = {
      query: parameters.filter(p => p.in === "query").map(p => p.name),
      idempotencyKey: parameters.some(p => p.in === "header" && p.name === "Idempotency-Key" && p.required),
      ...(body ? {body: body.required ?? []} : {}),
    };
  }
}

const digest = createHash("sha256").update(raw).digest("hex").slice(0, 12);
const lines = Object.keys(routes).sort().map(key => `  ${JSON.stringify(key)}: ${JSON.stringify(routes[key])},`);
const text = `// Generated by scripts/gen-routes.mjs from rokku-backend openapi/public.json (sha256 ${digest}). Do not edit.\n` +
  `export const ROUTES = {\n${lines.join("\n")}\n};\n`;
if (mode === "--check") {
  const current = readFileSync(OUTPUT, "utf8").replace(/^.*\n/, ""), next = text.replace(/^.*\n/, "");
  if (current !== next) { process.stderr.write("lib/routes.generated.mjs is out of date; rerun without --check\n"); process.exit(1); }
  process.stdout.write("lib/routes.generated.mjs matches this spec\n");
} else {
  writeFileSync(OUTPUT, text);
  process.stdout.write(`Wrote ${Object.keys(routes).length} routes (spec sha256 ${digest})\n`);
}
